//! Install the `jiji` terminal entry point.
//!
//! The launcher is a small shell script generated at install time (nothing
//! is bundled), so installing from a dev build works the same as from a
//! release. It forwards arguments to the app's embedded CLI. Its `open`
//! command resolves paths and uses Launch Services, which reaches the
//! running instance or launches one — either way the path arrives as a
//! macOS open-documents event.

use std::path::{Path, PathBuf};

use super::{CommandError, HostResult};

/// Identifies a launcher we generated, so status and uninstall never
/// mistake (or remove) somebody else's `jiji` binary.
const LAUNCHER_MARKER: &str = "jiji-cli-launcher";
const CURRENT_LAUNCHER_MARKER: &str = "jiji-cli-launcher-v2";

/// Where the launcher may live, in preference order. Both are on the
/// default PATH for their audience; a launcher nobody can run is worse
/// than none, so there is no ~/bin fallback.
const INSTALL_DIRS: &[&str] = &["/usr/local/bin", "/opt/homebrew/bin"];

#[derive(Debug, Clone, PartialEq, Default)]
pub struct CliStatus {
    pub installed: bool,
    pub upgrade_available: bool,
    /// Where our launcher lives, when installed.
    pub path: Option<String>,
    /// A foreign `jiji` occupying a launcher location; installing would
    /// clobber it, so the UI explains instead of offering.
    pub conflict: Option<String>,
}

/// Forward every argument without interpretation. With no arguments the
/// old launcher behavior remains: open the repository containing the cwd.
fn launcher_script(executable: &Path) -> String {
    let executable = shell_quote(&executable.to_string_lossy());
    format!(
        r#"#!/bin/sh
# {CURRENT_LAUNCHER_MARKER} — generated by Jiji.app; update or remove it from
# Jiji's command palette.
set -eu
if [ "$#" -eq 0 ]; then set -- open .; fi
exec {executable} "$@"
"#
    )
}

fn unsupported() -> CommandError {
    CommandError::new(
        "unsupported_platform",
        "The command-line launcher is only available on macOS",
    )
}

/// The launcher's install state. Refusing off macOS (rather than reporting
/// "not installed") is what keeps every install affordance off screen
/// there.
pub fn cli_status() -> HostResult<CliStatus> {
    if cfg!(target_os = "macos") {
        Ok(scan_install_dirs())
    } else {
        Err(unsupported())
    }
}

fn scan_install_dirs() -> CliStatus {
    for dir in INSTALL_DIRS {
        let candidate = Path::new(dir).join("jiji");
        if !candidate.exists() {
            continue;
        }
        let body = std::fs::read_to_string(&candidate).unwrap_or_default();
        let path = Some(candidate.to_string_lossy().into_owned());
        return if body.contains(LAUNCHER_MARKER) {
            CliStatus {
                installed: true,
                upgrade_available: !body.contains(CURRENT_LAUNCHER_MARKER),
                path,
                conflict: None,
            }
        } else {
            CliStatus {
                conflict: path,
                ..CliStatus::default()
            }
        };
    }
    CliStatus::default()
}

pub fn install_cli() -> HostResult<CliStatus> {
    if !cfg!(target_os = "macos") {
        return Err(unsupported());
    }
    let status = scan_install_dirs();
    if let Some(conflict) = status.conflict {
        return Err(CommandError::new(
            "cli_conflict",
            format!("A different jiji command is already installed at {conflict}"),
        ));
    }
    let executable = std::env::current_exe()
        .map_err(|err| CommandError::new("install_failed", err.to_string()))?;
    let script = launcher_script(&executable);

    // Reinstalling refreshes in place; otherwise the first direct write
    // that lands wins. Only permission trouble falls through to the
    // escalated path — a missing directory does too (creating it needs
    // root anyway).
    let targets: Vec<PathBuf> = match status.path {
        Some(existing) => vec![PathBuf::from(existing)],
        None => INSTALL_DIRS
            .iter()
            .map(|dir| Path::new(dir).join("jiji"))
            .collect(),
    };
    for target in &targets {
        if write_executable(target, &script).is_ok() {
            return Ok(scan_install_dirs());
        }
    }
    escalated_install(&script)?;
    Ok(scan_install_dirs())
}

pub fn uninstall_cli() -> HostResult<CliStatus> {
    if !cfg!(target_os = "macos") {
        return Err(unsupported());
    }
    let status = scan_install_dirs();
    let Some(path) = status.path.clone() else {
        return Ok(status);
    };
    match std::fs::remove_file(&path) {
        Ok(()) => Ok(scan_install_dirs()),
        Err(err) if err.kind() == std::io::ErrorKind::PermissionDenied => {
            run_privileged(
                &format!("rm {}", shell_quote(&path)),
                "remove the jiji command",
            )?;
            Ok(scan_install_dirs())
        }
        Err(err) => Err(CommandError::new(
            "uninstall_failed",
            format!("Could not remove {path}: {err}"),
        )),
    }
}

fn write_executable(target: &Path, script: &str) -> std::io::Result<()> {
    std::fs::write(target, script)?;
    // Only macOS installs a launcher, but the refusal elsewhere is a
    // runtime check, so this still has to build where there are no Unix
    // permissions.
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt as _;
        std::fs::set_permissions(target, std::fs::Permissions::from_mode(0o755))?;
    }
    Ok(())
}

/// Neither install dir was writable: stage the script somewhere we can
/// write and let `install` move it as root behind the native admin prompt.
fn escalated_install(script: &str) -> HostResult<()> {
    let staged = std::env::temp_dir().join("jiji-cli-launcher.sh");
    std::fs::write(&staged, script).map_err(|err| {
        CommandError::new(
            "install_failed",
            format!("Could not stage the launcher: {err}"),
        )
    })?;
    let result = run_privileged(
        &format!(
            "mkdir -p /usr/local/bin && install -m 0755 {} /usr/local/bin/jiji",
            shell_quote(&staged.to_string_lossy()),
        ),
        "install the jiji command",
    );
    let _ = std::fs::remove_file(&staged);
    result
}

/// One shell command behind the native administrator prompt. Declining the
/// prompt is a decision, not a failure — it gets its own code so the UI
/// can stay quiet about it.
fn run_privileged(shell_cmd: &str, purpose: &str) -> HostResult<()> {
    let apple = format!(
        r#"do shell script "{}" with administrator privileges"#,
        shell_cmd.replace('\\', "\\\\").replace('"', "\\\""),
    );
    let output = std::process::Command::new("osascript")
        .args(["-e", &apple])
        .output()
        .map_err(|err| {
            CommandError::new("install_failed", format!("Could not {purpose}: {err}"))
        })?;
    if output.status.success() {
        return Ok(());
    }
    let stderr = String::from_utf8_lossy(&output.stderr);
    if stderr.contains("User canceled") {
        return Err(CommandError::new("install_canceled", "Canceled"));
    }
    Err(CommandError::new(
        "install_failed",
        format!("Could not {purpose}: {}", stderr.trim()),
    ))
}

fn shell_quote(path: &str) -> String {
    format!("'{}'", path.replace('\'', r"'\''"))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn launcher_script_is_identifiable_and_targets_the_embedded_cli() {
        let script = launcher_script(Path::new(
            "/Applications/Jiji.app/Contents/MacOS/jiji-desktop",
        ));
        assert!(script.starts_with("#!/bin/sh"));
        assert!(script.contains(LAUNCHER_MARKER));
        assert!(script.contains(CURRENT_LAUNCHER_MARKER));
        assert!(script.contains("exec '/Applications/Jiji.app/Contents/MacOS/jiji-desktop' \"$@\""));
    }

    #[cfg(unix)]
    #[test]
    fn installed_launcher_preserves_arguments_and_opens_the_cwd_by_default() {
        use std::os::unix::fs::PermissionsExt;
        let dir = std::env::temp_dir().join(format!("jiji-launcher-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        let executable = dir.join("Jiji's executable");
        std::fs::write(&executable, "#!/bin/sh\nprintf '%s\\n' \"$@\"\n").unwrap();
        std::fs::set_permissions(&executable, std::fs::Permissions::from_mode(0o755)).unwrap();
        let launcher = dir.join("jiji");
        std::fs::write(&launcher, launcher_script(&executable)).unwrap();
        let result = std::process::Command::new("sh")
            .arg(&launcher)
            .args(["land", "ws/a branch", "--dry-run", "--json"])
            .output()
            .unwrap();
        assert!(result.status.success());
        assert_eq!(
            String::from_utf8(result.stdout).unwrap(),
            "land\nws/a branch\n--dry-run\n--json\n"
        );
        let result = std::process::Command::new("sh")
            .arg(&launcher)
            .output()
            .unwrap();
        assert_eq!(String::from_utf8(result.stdout).unwrap(), "open\n.\n");
        let _ = std::fs::remove_dir_all(dir);
    }
}
