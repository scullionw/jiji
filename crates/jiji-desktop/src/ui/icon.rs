macro_rules! icons {
    ($($variant:ident => $name:literal, $body:literal;)*) => {
        #[derive(Clone, Copy, PartialEq, Eq, Debug, Hash)]
        pub enum IconName {
            $($variant,)*
        }

        impl IconName {
            fn key(self) -> &'static str {
                match self {
                    $(IconName::$variant => $name,)*
                }
            }

            fn body(name: &str) -> Option<&'static str> {
                match name {
                    $($name => Some($body),)*
                    _ => None,
                }
            }
        }
    };
}

