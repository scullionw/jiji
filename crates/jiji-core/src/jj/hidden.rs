//! Reversible shelving without bookmarks or Git refs advertising the shelf.
//!
//! jj abandonment alone leaves refs/jj/keep/* reachable by `git log --all`.
//! Before removing those refs, preserve their complete object closure in a
//! pack protected by a .keep file. Neither Git GC nor jj operation GC removes
//! that pack. jj's own GC can *recreate* the refs; repeating hide removes them
//! again. We deliberately retain jj's operation log and Git's HEAD reflog.

use std::fs::{self, File, OpenOptions};
use std::io::Write;
use std::path::PathBuf;
use std::process::{Command, Stdio};

use serde::{Deserialize, Serialize};

use super::*;

#[derive(Clone, Debug, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct HiddenChange {
    pub change_id: String,
    pub commit_id: String,
    pub description: String,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct HiddenBookmark {
    pub name: String,
    pub commit_id: String,
}

/// One hide operation. Any member's unambiguous change/commit ID prefix can
/// recover the entire group, preserving its original IDs, trees and parents.
#[derive(Clone, Debug, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct HiddenEntry {
    pub id: String,
    pub changes: Vec<HiddenChange>,
    pub bookmarks: Vec<HiddenBookmark>,
    pub hidden_at: String,
    // Old versions must also disappear from Git, not just the current commit.
    pub git_roots: Vec<String>,
    pub pack: Option<String>,
}

#[derive(Serialize, Deserialize)]
struct Archive {
    version: u32,
    entries: Vec<HiddenEntry>,
}

impl Default for Archive {
    fn default() -> Self {
        Self {
            version: 1,
            entries: Vec::new(),
        }
    }
}

impl JjBackend {
    /// Read the shared repository archive, including from another workspace.
    pub fn hidden(&self, path: &Path) -> Result<Vec<HiddenEntry>, BackendError> {
        let (workspace, _) = self.load_repo_at_head(path)?;
        Ok(read_archive(&archive_path(&workspace))?.entries)
    }

    pub fn hide(
        &self,
        path: &Path,
        revision: &str,
        stack: bool,
        dry_run: bool,
    ) -> Result<HiddenEntry, BackendError> {
        let (_write, mut workspace, mut repo) = self.load_repo_for_write(path)?;
        let archive_path = archive_path(&workspace);
        let _lock = archive_lock(&archive_path, dry_run)?;
        let mut archive = read_archive(&archive_path)?;
        let git = HiddenGit::new(&workspace, &repo)?;
        if !dry_run {
            repo = sync_workspace(&mut workspace, repo)?;
        }

        // Repeating hide also repairs retention refs regenerated by `jj util gc`.
        if let Some(index) = find_entry(&archive, revision)? {
            let entry = archive.entries[index].clone();
            let visible = visible_ids(repo.as_ref())?;
            let ambiguous = if let Some(prefix) = change_id_prefix(revision) {
                matches!(
                    pollster::block_on(repo.resolve_change_id_prefix(&prefix))
                        .map_err(mutation_err)?,
                    PrefixResolution::AmbiguousMatch
                )
            } else if let Some(prefix) = HexPrefix::try_from_hex(revision) {
                matches!(
                    pollster::block_on(repo.index().resolve_commit_id_prefix(&prefix))
                        .map_err(mutation_err)?,
                    PrefixResolution::AmbiguousMatch
                )
            } else {
                false
            };
            if ambiguous {
                return Err(failed(
                    "this ID prefix is ambiguous in jj; use a longer hidden change ID",
                ));
            }
            if let Ok(expr) = resolve_revset_text(&workspace, repo.as_ref(), revision) {
                if collect_revset(expr, repo.as_ref(), 2)?
                    .iter()
                    .any(|id| visible.contains(&id.hex()))
                {
                    return Err(failed("this ID also resolves to visible work; use a longer ID, or unhide the archived version first"));
                }
            }
            if entry.changes.iter().any(|c| visible.contains(&c.commit_id)) {
                return Err(failed(
                    "this archive is visible again; unhide it before hiding a new version",
                ));
            }
            let affected = git.affected(&entry.git_roots)?;
            if affected.iter().any(|id| visible.contains(id)) {
                return Err(failed("an archived version or descendant is visible in jj again; resolve it before hiding"));
            }
            git.check_refs(&affected, &HashMap::new(), false)?;
            if !dry_run {
                // Preserve any newer obsolete descendants too, before deleting refs.
                let pack = git.protect(&affected)?;
                archive.entries[index].pack = Some(pack);
                write_archive(&archive_path, &archive)?;
                git.remove_keep_refs(&affected)?;
            }
            return Ok(archive.entries[index].clone());
        }

        let expr = resolve_revset_text(&workspace, repo.as_ref(), revision)
            .map_err(BackendError::RevsetInvalid)?;
        let selected = collect_revset(expr, repo.as_ref(), 2)?;
        let [head] = selected.as_slice() else {
            return Err(failed(
                "hide expects exactly one visible revision; use --stack to hide its stack",
            ));
        };
        let head = repo.store().get_commit(head).map_err(mutation_err)?;
        let visible = visible_ids(repo.as_ref())?;
        if !visible.contains(&head.id().hex()) {
            return Err(failed("the selected revision is already hidden by jj"));
        }
        check_mutable(&workspace, repo.as_ref(), &head, revision)?;
        let selected = RevsetExpression::commit(head.id().clone());
        let selected = if stack {
            let immutable = immutable_heads_expression(&workspace, repo.as_ref())?
                .union(&RevsetExpression::root())
                .ancestors();
            selected.ancestors().minus(&immutable)
        } else {
            selected
        };
        let commits = commits_in(repo.as_ref(), &selected)?;
        let affected_visible = commits_in(repo.as_ref(), &selected.descendants())?;
        let affected_ids: HashSet<_> = affected_visible.iter().map(|c| c.id().hex()).collect();
        // Even single-change abandonment rewrites descendants. Refuse to change
        // immutable history or leave another workspace showing the hidden work.
        for commit in &affected_visible {
            check_mutable(
                &workspace,
                repo.as_ref(),
                commit,
                &commit.change_id().reverse_hex(),
            )?;
        }
        for (name, id) in repo.view().wc_commit_ids() {
            if name != workspace.workspace_name() && affected_ids.contains(&id.hex()) {
                return Err(failed(format!(
                    "workspace {} uses this work; move it away before hiding",
                    name.as_str()
                )));
            }
        }
        let selected_ids: HashSet<_> = commits.iter().map(|c| c.id().hex()).collect();
        let mut roots = BTreeSet::new();
        for commit in &commits {
            if let Some(targets) = pollster::block_on(repo.resolve_change_id(commit.change_id()))
                .map_err(mutation_err)?
            {
                if targets.is_divergent() {
                    return Err(failed(
                        "cannot hide a divergent change; resolve the divergence first",
                    ));
                }
                roots.extend(targets.targets.into_iter().map(|(id, _)| id.hex()));
            }
            roots.insert(commit.id().hex());
        }
        let mut bookmarks = Vec::new();
        for (name, target) in repo.view().local_bookmarks() {
            if target
                .added_ids()
                .any(|id| selected_ids.contains(&id.hex()))
            {
                let Some(id) = target.as_normal() else {
                    return Err(failed(format!(
                        "bookmark {} is conflicted; resolve it before hiding",
                        name.as_str()
                    )));
                };
                bookmarks.push(HiddenBookmark {
                    name: name.as_str().into(),
                    commit_id: id.hex(),
                });
            }
        }
        // Remote bookmarks may exist without corresponding local Git refs.
        for (symbol, reference) in repo.view().all_remote_bookmarks() {
            if symbol.remote != REMOTE_NAME_FOR_LOCAL_GIT_REPO
                && reference
                    .target
                    .added_ids()
                    .any(|id| affected_ids.contains(&id.hex()))
            {
                return Err(failed(format!("remote bookmark {symbol} exposes this work; only unpublished work can be hidden")));
            }
        }
        let roots: Vec<_> = roots.into_iter().collect();
        let affected = git.affected(&roots)?;
        // Snapshotting can move jj bookmarks before their Git refs have been
        // exported. Permit those exact old Git targets, too: finish_mutation
        // will delete/rebase them using jj's recorded export state.
        let mut moving_refs = HashMap::new();
        for (name, target) in repo.view().git_refs() {
            if let Some(bookmark) = name.as_str().strip_prefix("refs/heads/") {
                let local = repo.view().get_local_bookmark(RefName::new(bookmark));
                if local
                    .as_normal()
                    .is_some_and(|id| affected_ids.contains(&id.hex()))
                {
                    if let Some(id) = target.as_normal() {
                        moving_refs.insert(name.as_str().to_owned(), id.hex());
                    }
                }
            }
        }
        git.check_refs(
            &affected,
            &moving_refs,
            is_colocated(&workspace, repo.store()),
        )?;
        let mut entry = HiddenEntry {
            id: head.change_id().reverse_hex(),
            changes: commits
                .iter()
                .map(|c| HiddenChange {
                    change_id: c.change_id().reverse_hex(),
                    commit_id: c.id().hex(),
                    description: c.description().lines().next().unwrap_or("").into(),
                })
                .collect(),
            bookmarks,
            hidden_at: chrono::Utc::now().to_rfc3339(),
            git_roots: roots,
            pack: None,
        };
        if dry_run {
            return Ok(entry);
        }

        // Durability order is intentional: objects, then recovery record, then
        // jj mutation, and finally ref removal. A failure always leaves a way
        // back, including if checkout fails after the jj operation commits.
        entry.pack = Some(git.protect(&affected)?);
        archive.entries.push(entry.clone());
        write_archive(&archive_path, &archive)?;
        let mut tx = repo.start_transaction();
        for commit in &commits {
            tx.repo_mut().record_abandoned_commit(commit);
        }
        let options = RebaseOptions {
            rewrite_refs: RewriteRefsOptions {
                delete_abandoned_bookmarks: true,
            },
            ..Default::default()
        };
        pollster::block_on(
            tx.repo_mut()
                .rebase_descendants_with_options(&RevsetExpression::none(), &options, |_, _| {}),
        )
        .map_err(mutation_err)?;
        let new_repo = finish_mutation(&mut workspace, &repo, tx, "hide changes with jiji".into())?;
        // Failed exports or concurrent writers must never become false success.
        let remaining = git.affected(&entry.git_roots)?;
        let visible = visible_ids(new_repo.as_ref())?;
        if remaining.iter().any(|id| visible.contains(id)) {
            return Err(failed(
                "some hidden work is still visible in jj; the recovery archive has been kept",
            ));
        }
        git.check_refs(&remaining, &HashMap::new(), false)?;
        if !remaining.is_subset(&affected) {
            entry.pack = Some(git.protect(&remaining)?);
            *archive.entries.last_mut().unwrap() = entry.clone();
            write_archive(&archive_path, &archive)?;
        }
        git.remove_keep_refs(&remaining)?;
        Ok(entry)
    }

    pub fn unhide(
        &self,
        path: &Path,
        id: &str,
        dry_run: bool,
    ) -> Result<HiddenEntry, BackendError> {
        let (_write, mut workspace, mut repo) = self.load_repo_for_write(path)?;
        let archive_path = archive_path(&workspace);
        let _lock = archive_lock(&archive_path, dry_run)?;
        let mut archive = read_archive(&archive_path)?;
        let index = find_entry(&archive, id)?
            .ok_or_else(|| failed(format!("no hidden change matches {id}; use jiji hidden")))?;
        let entry = archive.entries[index].clone();
        if !dry_run {
            repo = sync_workspace(&mut workspace, repo)?;
        }
        for bookmark in &entry.bookmarks {
            let target = repo.view().get_local_bookmark(RefName::new(&bookmark.name));
            if target.is_present()
                && target.as_normal().map(|id| id.hex()).as_deref() != Some(&bookmark.commit_id)
            {
                return Err(failed(format!(
                    "bookmark {} has been reused; rename it before unhiding",
                    bookmark.name
                )));
            }
        }
        let mut commits = Vec::new();
        for change in &entry.changes {
            let commit = repo
                .store()
                .get_commit(&commit_id(&change.commit_id)?)
                .map_err(mutation_err)?;
            if commit.change_id().reverse_hex() != change.change_id {
                return Err(failed(
                    "archived change metadata no longer matches the repository",
                ));
            }
            if let Some(targets) = pollster::block_on(repo.resolve_change_id(commit.change_id()))
                .map_err(mutation_err)?
            {
                if targets
                    .visible_with_offsets()
                    .any(|(_, id)| id != commit.id())
                {
                    return Err(failed(format!(
                        "change {} has another visible version; resolve it before unhiding",
                        change.change_id
                    )));
                }
            }
            commits.push(commit);
        }
        // Restoring a child also restores its ancestors. Do not implicitly
        // unhide work put aside by a separate hide operation.
        // Read from the object store, not the revset index: operation pruning
        // and reindexing may have forgotten these otherwise durable objects.
        let mut ancestors = HashSet::new();
        let mut pending: Vec<_> = commits.iter().map(|c| c.id().clone()).collect();
        while let Some(id) = pending.pop() {
            if ancestors.insert(id.hex()) {
                let commit = repo.store().get_commit(&id).map_err(mutation_err)?;
                pending.extend_from_slice(commit.parent_ids());
            }
        }
        for (other_index, other) in archive.entries.iter().enumerate() {
            if other_index != index && other.git_roots.iter().any(|id| ancestors.contains(id)) {
                return Err(failed(format!(
                    "unhide {} first; it is an archived ancestor",
                    other.id
                )));
            }
        }
        if dry_run {
            return Ok(entry);
        }
        let mut tx = repo.start_transaction();
        pollster::block_on(tx.repo_mut().add_heads(&commits)).map_err(mutation_err)?;
        for bookmark in &entry.bookmarks {
            tx.repo_mut().set_local_bookmark_target(
                RefName::new(&bookmark.name),
                RefTarget::normal(commit_id(&bookmark.commit_id)?),
            );
        }
        finish_mutation(&mut workspace, &repo, tx, "unhide changes with jiji".into())?;
        // Unbookmarked changes need their ordinary jj retention refs restored
        // too, so they reappear in Git's --all view.
        let git = HiddenGit::new(&workspace, &repo)?;
        git.restore_keep_refs(&entry.changes)?;
        let restored_refs: HashMap<_, _> = git.refs()?.into_iter().collect();
        for bookmark in &entry.bookmarks {
            if restored_refs.get(&format!("refs/heads/{}", bookmark.name))
                != Some(&bookmark.commit_id)
            {
                return Err(failed(format!(
                    "could not export restored bookmark {}; the recovery archive has been kept",
                    bookmark.name
                )));
            }
        }
        archive.entries.remove(index);
        write_archive(&archive_path, &archive)?;
        Ok(entry)
    }
}

fn failed(message: impl Into<String>) -> BackendError {
    BackendError::MutationFailed(message.into())
}

fn commits_in(
    repo: &dyn Repo,
    expr: &Arc<ResolvedRevsetExpression>,
) -> Result<Vec<Commit>, BackendError> {
    expr.clone()
        .evaluate(repo)
        .map_err(mutation_err)?
        .iter_blocking()
        .map(|id| {
            repo.store()
                .get_commit(&id.map_err(mutation_err)?)
                .map_err(mutation_err)
        })
        .collect()
}

fn visible_ids(repo: &dyn Repo) -> Result<HashSet<String>, BackendError> {
    RevsetExpression::visible_heads()
        .ancestors()
        .evaluate(repo)
        .map_err(mutation_err)?
        .iter_blocking()
        .map(|id| id.map(|id| id.hex()).map_err(mutation_err))
        .collect()
}

fn archive_path(workspace: &Workspace) -> PathBuf {
    workspace.repo_path().join("jiji/hidden.json")
}

fn archive_lock(path: &Path, dry_run: bool) -> Result<Option<File>, BackendError> {
    if dry_run {
        return Ok(None);
    }
    fs::create_dir_all(path.parent().unwrap()).map_err(mutation_err)?;
    let file = OpenOptions::new()
        .create(true)
        .truncate(false)
        .read(true)
        .write(true)
        .open(path.with_extension("lock"))
        .map_err(mutation_err)?;
    // A lock released a moment ago can linger: a process another thread
    // is forking holds a copy of the descriptor until it execs. Wait a
    // little before calling the archive busy.
    let deadline = std::time::Instant::now() + std::time::Duration::from_secs(2);
    loop {
        match file.try_lock() {
            Ok(()) => return Ok(Some(file)),
            Err(fs::TryLockError::WouldBlock) if std::time::Instant::now() < deadline => {
                std::thread::sleep(std::time::Duration::from_millis(20));
            }
            Err(err) => {
                return Err(failed(format!(
                    "another hide/unhide command owns the archive lock: {err}"
                )))
            }
        }
    }
}

fn read_archive(path: &Path) -> Result<Archive, BackendError> {
    let bytes = match fs::read(path) {
        Ok(bytes) => bytes,
        Err(err) if err.kind() == std::io::ErrorKind::NotFound => return Ok(Archive::default()),
        Err(err) => return Err(mutation_err(err)),
    };
    let archive: Archive = serde_json::from_slice(&bytes)
        .map_err(|err| failed(format!("could not read {}: {err}", path.display())))?;
    if archive.version != 1
        || archive.entries.iter().any(|e| {
            e.changes.is_empty()
                || e.id.len() != 32
                || change_id_prefix(&e.id).is_none()
                || e.changes.iter().any(|c| {
                    c.change_id.len() != 32
                        || change_id_prefix(&c.change_id).is_none()
                        || !valid_commit_id(&c.commit_id)
                })
                || e.git_roots.iter().any(|id| !valid_commit_id(id))
                || e.bookmarks.iter().any(|b| !valid_commit_id(&b.commit_id))
        })
    {
        return Err(failed(format!(
            "unsupported or invalid hidden archive: {}",
            path.display()
        )));
    }
    Ok(archive)
}

fn valid_commit_id(id: &str) -> bool {
    id.len() == 40 && id.bytes().all(|c| c.is_ascii_hexdigit())
}

fn commit_id(id: &str) -> Result<CommitId, BackendError> {
    CommitId::try_from_hex(id).ok_or_else(|| failed("invalid archived commit ID"))
}

fn write_archive(path: &Path, archive: &Archive) -> Result<(), BackendError> {
    let mut file = tempfile::NamedTempFile::new_in(path.parent().unwrap()).map_err(mutation_err)?;
    serde_json::to_writer_pretty(&mut file, archive).map_err(mutation_err)?;
    file.write_all(b"\n").map_err(mutation_err)?;
    file.as_file().sync_all().map_err(mutation_err)?;
    file.persist(path).map_err(mutation_err)?;
    #[cfg(unix)]
    File::open(path.parent().unwrap())
        .and_then(|f| f.sync_all())
        .map_err(mutation_err)?;
    Ok(())
}

fn find_entry(archive: &Archive, prefix: &str) -> Result<Option<usize>, BackendError> {
    if prefix.is_empty() {
        return Err(failed("a hidden change ID is required"));
    }
    let mut matches = archive
        .entries
        .iter()
        .enumerate()
        .filter(|(_, entry)| {
            entry
                .changes
                .iter()
                .any(|c| c.change_id.starts_with(prefix) || c.commit_id.starts_with(prefix))
        })
        .map(|(i, _)| i);
    let result = matches.next();
    if matches.next().is_some() {
        return Err(failed(format!(
            "hidden change prefix {prefix} is ambiguous; use a longer ID"
        )));
    }
    Ok(result)
}

struct HiddenGit {
    options: git::GitSubprocessOptions,
    directory: PathBuf,
}

impl HiddenGit {
    fn new(workspace: &Workspace, repo: &ReadonlyRepo) -> Result<Self, BackendError> {
        Ok(Self {
            options: git::GitSubprocessOptions::from_settings(workspace.settings())
                .map_err(mutation_err)?,
            directory: git::get_git_backend(repo.store())
                .map_err(|_| failed("hide requires a Git-backed jj repository"))?
                .git_repo_path()
                .to_owned(),
        })
    }

    fn command(&self, args: &[&str]) -> Command {
        let mut cmd = Command::new(&self.options.executable_path);
        cmd.arg("--no-replace-objects")
            .args([
                "-c",
                "core.fsmonitor=false",
                "-c",
                "submodule.recurse=false",
            ])
            .arg("--git-dir")
            .arg(&self.directory)
            .args(args)
            .env("LC_ALL", "C")
            .envs(&self.options.environment)
            .stdin(Stdio::null())
            .stdout(Stdio::piped())
            .stderr(Stdio::piped());
        cmd
    }

    fn run(&self, args: &[&str]) -> Result<String, BackendError> {
        check_output(self.command(args).output().map_err(mutation_err)?)
    }

    /// Git's graph includes obsolete descendants that jj's visible revsets
    /// omit. Walk parent-first so a ref to *any* descendant is recognized.
    fn affected(&self, roots: &[String]) -> Result<HashSet<String>, BackendError> {
        let graph = self.run(&["rev-list", "--all", "--reflog", "--topo-order", "--parents"])?;
        let mut affected: HashSet<_> = roots.iter().cloned().collect();
        for line in graph.lines().rev() {
            let mut parts = line.split_whitespace();
            if let Some(id) = parts.next() {
                if parts.any(|parent| affected.contains(parent)) {
                    affected.insert(id.to_owned());
                }
            }
        }
        Ok(affected)
    }

    fn refs(&self) -> Result<Vec<(String, String)>, BackendError> {
        let refs = self.run(&[
            "for-each-ref",
            "--format=%(refname) %(objectname) %(objecttype)",
        ])?;
        let mut result = Vec::new();
        for line in refs.lines() {
            let fields: Vec<_> = line.split_whitespace().collect();
            let [name, id, kind] = fields.as_slice() else {
                return Err(failed("Git returned an invalid reference"));
            };
            if *kind == "tag" {
                // Peel recursively: annotated tags can point to other tags.
                if let Ok(id) = self.run(&["rev-parse", "--verify", &format!("{name}^{{commit}}")])
                {
                    result.push(((*name).into(), id.trim().into()));
                }
            } else {
                result.push(((*name).into(), (*id).into()));
            }
        }
        Ok(result)
    }

    fn check_refs(
        &self,
        affected: &HashSet<String>,
        moving: &HashMap<String, String>,
        move_head: bool,
    ) -> Result<(), BackendError> {
        for (name, id) in self.refs()? {
            if affected.contains(&id)
                && !name.starts_with("refs/jj/keep/")
                && moving.get(&name) != Some(&id)
            {
                return Err(failed(format!(
                    "Git ref {name} exposes this work; remove or move that ref before hiding"
                )));
            }
        }
        if let Ok(head) = self.run(&["rev-parse", "--verify", "HEAD"]) {
            if affected.contains(head.trim()) && !move_head {
                return Err(failed(
                    "Git HEAD still exposes this work; move its checkout before hiding",
                ));
            }
        }
        let worktrees = self.run(&["worktree", "list", "--porcelain"])?;
        if worktrees
            .lines()
            .filter(|line| line.starts_with("worktree "))
            .count()
            > 1
        {
            return Err(failed(
                "hide is not supported while the backing Git repository has linked worktrees",
            ));
        }
        Ok(())
    }

    /// Stream the complete closure to a protected pack, without creating refs.
    /// Full ancestry keeps recovery independent of future rebases and pruning.
    fn protect(&self, ids: &HashSet<String>) -> Result<String, BackendError> {
        let mut revisions = tempfile::NamedTempFile::new().map_err(mutation_err)?;
        for id in ids {
            writeln!(revisions, "{id}").map_err(mutation_err)?;
        }
        let pack = tempfile::NamedTempFile::new().map_err(mutation_err)?;
        let output = self
            .command(&["pack-objects", "--revs", "--stdout"])
            .stdin(File::open(revisions.path()).map_err(mutation_err)?)
            .stdout(pack.reopen().map_err(mutation_err)?)
            .output()
            .map_err(mutation_err)?;
        check_output(output)?;
        let output = self
            .command(&["index-pack", "--stdin", "--keep=jiji hidden changes"])
            .stdin(File::open(pack.path()).map_err(mutation_err)?)
            .output()
            .map_err(mutation_err)?;
        let result = check_output(output)?;
        let hash = result
            .split_whitespace()
            .last()
            .ok_or_else(|| failed("Git returned no archive pack ID"))?;
        if !valid_commit_id(hash) {
            return Err(failed("Git returned an invalid archive pack ID"));
        }
        Ok(hash.into())
    }

    fn update_refs(&self, commands: &str) -> Result<(), BackendError> {
        let mut input = tempfile::NamedTempFile::new().map_err(mutation_err)?;
        input.write_all(commands.as_bytes()).map_err(mutation_err)?;
        let output = self
            .command(&["update-ref", "--no-deref", "--stdin"])
            .stdin(File::open(input.path()).map_err(mutation_err)?)
            .output()
            .map_err(mutation_err)?;
        check_output(output)?;
        Ok(())
    }

    fn remove_keep_refs(&self, affected: &HashSet<String>) -> Result<(), BackendError> {
        let mut commands = String::from("start\n");
        for (name, id) in self.refs()? {
            if name.starts_with("refs/jj/keep/") && affected.contains(&id) {
                commands.push_str(&format!("delete {name} {id}\n"));
            }
        }
        commands.push_str("prepare\ncommit\n");
        self.update_refs(&commands)
    }

    fn restore_keep_refs(&self, changes: &[HiddenChange]) -> Result<(), BackendError> {
        let mut commands = String::from("start\n");
        for change in changes {
            commands.push_str(&format!("update refs/jj/keep/{0} {0}\n", change.commit_id));
        }
        commands.push_str("prepare\ncommit\n");
        self.update_refs(&commands)
    }
}

fn check_output(output: std::process::Output) -> Result<String, BackendError> {
    if !output.status.success() {
        return Err(failed(format!(
            "Git archive operation failed: {}",
            String::from_utf8_lossy(&output.stderr).trim()
        )));
    }
    Ok(String::from_utf8_lossy(&output.stdout).into_owned())
}

