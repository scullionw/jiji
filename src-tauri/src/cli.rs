//! Install the `jiji` terminal entry point and receive desktop-open requests.
//!
//! The launcher is a small shell script generated at install time (nothing
//! is bundled), so installing from a dev build works the same as from a
//! release. It forwards arguments to the app's embedded CLI. Its `open`
//! command resolves paths and uses Launch Services, which
//! reaches the running instance or launches one — either way the path
//! arrives as a macOS open-documents event (`RunEvent::Opened`).
//!
//! Delivery to the frontend is pull-based to survive the cold-start race:
//! the event can fire before the webview has subscribed to anything, so
//! the handler parks the path in [`PendingOpen`] and pings; the frontend
//! drains on the ping and once at bootstrap, and the mutex take makes
//! double delivery impossible.

use std::path::{Path, PathBuf};
use std::sync::Mutex;

use serde::Serialize;
use tauri::{AppHandle, Emitter as _, Manager as _, State};

use crate::commands::CommandError;

pub const CLI_OPEN_REQUEST_EVENT: &str = "cli://open-request";

/// Identifies a launcher we generated, so status and uninstall never
/// mistake (or remove) somebody else's `jiji` binary.
const LAUNCHER_MARKER: &str = "jiji-cli-launcher";
const CURRENT_LAUNCHER_MARKER: &str = "jiji-cli-launcher-v2";

/// Where the launcher may live, in preference order. Both are on the
/// default PATH for their audience (`/etc/paths` and Homebrew's shellenv);
/// a launcher nobody can run is worse than none, so there is no ~/bin
/// fallback.
const INSTALL_DIRS: &[&str] = &["/usr/local/bin", "/opt/homebrew/bin"];

/// A repo path handed over by the launcher (or a folder dropped on the
/// Dock icon), parked until the frontend drains it.
#[derive(Default)]
pub struct PendingOpen(Mutex<Option<String>>);

#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct CliStatus {
    pub installed: bool,
    pub upgrade_available: bool,
    /// Where our launcher lives, when installed.
    pub path: Option<String>,
    /// A foreign `jiji` occupying a launcher location; installing would
    /// clobber it, so the UI explains instead of offering.
    pub conflict: Option<String>,
}

/// Forward every argument without interpretation. With no arguments the
/// old launcher behavior remains: open the repository containing the cwd.
fn launcher_script(executable: &Path) -> String {
    let executable = shell_quote(&executable.to_string_lossy());
    format!(
        r#"#!/bin/sh
# {CURRENT_LAUNCHER_MARKER} — generated by Jiji.app; update or remove it from
# Jiji's command palette.
set -eu
if [ "$#" -eq 0 ]; then set -- open .; fi
exec {executable} "$@"
"#
    )
}

/// The nearest ancestor that is a jj workspace root. The backend wants the
/// exact root, but "open this repo" from a terminal usually happens deep
/// inside it; a file selects its containing repo.
pub(crate) fn repo_root_for(path: &Path) -> Option<PathBuf> {
    let start = if path.is_dir() { path } else { path.parent()? };
    start
        .ancestors()
        .find(|dir| dir.join(".jj").is_dir())
        .map(Path::to_path_buf)
}

/// macOS open-documents events (the launcher's `open -b`, a folder dropped
/// on the Dock icon). Parks the resolved repo root and pings the frontend.
/// A path with no jj root passes through unresolved so `open_repo` can
/// refuse it with its usual friendly error.
pub fn handle_opened(app: &AppHandle, urls: Vec<tauri::Url>) {
    let Some(path) = urls.into_iter().find_map(|url| url.to_file_path().ok()) else {
        return;
    };
    let target = repo_root_for(&path).unwrap_or(path);
    let target = target.to_string_lossy().into_owned();
    *app.state::<PendingOpen>()
        .0
        .lock()
        .expect("pending open lock poisoned") = Some(target);
    if let Err(err) = app.emit(CLI_OPEN_REQUEST_EVENT, ()) {
        log::warn!("failed to emit cli open request: {err}");
    }
}

/// One-shot drain; the take is what guarantees the ping handler and the
/// bootstrap sweep can both run without opening the repo twice.
#[tauri::command]
pub fn take_pending_open(state: State<'_, PendingOpen>) -> Option<String> {
    state.0.lock().expect("pending open lock poisoned").take()
}

/// The launcher's install state. Erroring on non-macOS (rather than
/// reporting "not installed") is what keeps every install affordance off
/// screen there — the frontend treats a refusal as "no launcher here".
#[tauri::command]
pub fn cli_status() -> Result<CliStatus, CommandError> {
    #[cfg(not(target_os = "macos"))]
    return Err(CommandError::new(
        "unsupported_platform",
        "The command-line launcher is only available on macOS",
    ));
    #[cfg(target_os = "macos")]
    Ok(scan_install_dirs())
}

#[cfg(target_os = "macos")]
fn scan_install_dirs() -> CliStatus {
    for dir in INSTALL_DIRS {
        let candidate = Path::new(dir).join("jiji");
        if !candidate.exists() {
            continue;
        }
        let body = std::fs::read_to_string(&candidate).unwrap_or_default();
        let ours = body.contains(LAUNCHER_MARKER);
        let path = Some(candidate.to_string_lossy().into_owned());
        return if ours {
            CliStatus { installed: true, upgrade_available: !body.contains(CURRENT_LAUNCHER_MARKER), path, conflict: None }
        } else {
            CliStatus { installed: false, upgrade_available: false, path: None, conflict: path }
        };
    }
    CliStatus { installed: false, upgrade_available: false, path: None, conflict: None }
}

#[cfg(target_os = "macos")]
#[tauri::command]
pub fn install_cli(_app: AppHandle) -> Result<CliStatus, CommandError> {
    let status = scan_install_dirs();
    if let Some(conflict) = status.conflict {
        return Err(CommandError::new(
            "cli_conflict",
            format!("A different jiji command is already installed at {conflict}"),
        ));
    }
    let executable = std::env::current_exe().map_err(|err| CommandError::new("install_failed", err.to_string()))?;
    let script = launcher_script(&executable);

    // Reinstalling refreshes in place; otherwise the first direct write
    // that lands wins. Only permission trouble falls through to the
    // escalated path — a missing directory does too (creating it needs
    // root anyway).
    let targets: Vec<PathBuf> = match status.path {
        Some(existing) => vec![PathBuf::from(existing)],
        None => INSTALL_DIRS.iter().map(|dir| Path::new(dir).join("jiji")).collect(),
    };
    for target in &targets {
        if write_executable(target, &script).is_ok() {
            return Ok(scan_install_dirs());
        }
    }
    escalated_install(&script)?;
    Ok(scan_install_dirs())
}

#[cfg(target_os = "macos")]
#[tauri::command]
pub fn uninstall_cli() -> Result<CliStatus, CommandError> {
    let status = scan_install_dirs();
    let Some(path) = status.path else {
        return Ok(status);
    };
    match std::fs::remove_file(&path) {
        Ok(()) => Ok(scan_install_dirs()),
        Err(err) if err.kind() == std::io::ErrorKind::PermissionDenied => {
            run_privileged(&format!("rm {}", shell_quote(&path)), "remove the jiji command")?;
            Ok(scan_install_dirs())
        }
        Err(err) => Err(CommandError::new(
            "uninstall_failed",
            format!("Could not remove {path}: {err}"),
        )),
    }
}

