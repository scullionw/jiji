#[cfg(target_os = "macos")]
fn write_executable(target: &Path, script: &str) -> std::io::Result<()> {
    use std::os::unix::fs::PermissionsExt as _;
    std::fs::write(target, script)?;
    std::fs::set_permissions(target, std::fs::Permissions::from_mode(0o755))
}

/// Neither install dir was writable: stage the script somewhere we can
/// write and let `install` move it as root behind the native admin prompt.
#[cfg(target_os = "macos")]
fn escalated_install(script: &str) -> Result<(), CommandError> {
    let staged = std::env::temp_dir().join("jiji-cli-launcher.sh");
    std::fs::write(&staged, script).map_err(|err| {
        CommandError::new("install_failed", format!("Could not stage the launcher: {err}"))
    })?;
    let result = run_privileged(
        &format!(
            "mkdir -p /usr/local/bin && install -m 0755 {} /usr/local/bin/jiji",
            shell_quote(&staged.to_string_lossy()),
        ),
        "install the jiji command",
    );
    let _ = std::fs::remove_file(&staged);
    result
}

/// One shell command behind the native administrator prompt. Declining the
/// prompt is a decision, not a failure — it gets its own code so the UI
/// can stay quiet about it.
#[cfg(target_os = "macos")]
fn run_privileged(shell_cmd: &str, purpose: &str) -> Result<(), CommandError> {
    let apple = format!(
        r#"do shell script "{}" with administrator privileges"#,
        shell_cmd.replace('\\', "\\\\").replace('"', "\\\""),
    );
    let output = std::process::Command::new("osascript")
        .args(["-e", &apple])
        .output()
        .map_err(|err| CommandError::new("install_failed", format!("Could not {purpose}: {err}")))?;
    if output.status.success() {
        return Ok(());
    }
    let stderr = String::from_utf8_lossy(&output.stderr);
    if stderr.contains("User canceled") {
        return Err(CommandError::new("install_canceled", "Canceled"));
    }
    Err(CommandError::new(
        "install_failed",
        format!("Could not {purpose}: {}", stderr.trim()),
    ))
}

fn shell_quote(path: &str) -> String {
    format!("'{}'", path.replace('\'', r"'\''"))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn launcher_script_is_identifiable_and_targets_the_embedded_cli() {
        let script = launcher_script(Path::new("/Applications/Jiji.app/Contents/MacOS/jiji-desktop"));
        assert!(script.starts_with("#!/bin/sh"));
        assert!(script.contains(LAUNCHER_MARKER));
        assert!(script.contains(CURRENT_LAUNCHER_MARKER));
        assert!(script.contains("exec '/Applications/Jiji.app/Contents/MacOS/jiji-desktop' \"$@\""));
    }

    #[cfg(unix)]
    #[test]
    fn installed_launcher_preserves_arguments_and_opens_the_cwd_by_default() {
        use std::os::unix::fs::PermissionsExt;
        let dir = tempfile::tempdir().unwrap();
        let executable = dir.path().join("Jiji's executable");
        std::fs::write(&executable, "#!/bin/sh\nprintf '%s\\n' \"$@\"\n").unwrap();
        std::fs::set_permissions(&executable, std::fs::Permissions::from_mode(0o755)).unwrap();
        let launcher = dir.path().join("jiji");
        std::fs::write(&launcher, launcher_script(&executable)).unwrap();
        let result = std::process::Command::new("sh").arg(&launcher).args(["land", "ws/a branch", "--dry-run", "--json"]).output().unwrap();
        assert!(result.status.success());
        assert_eq!(String::from_utf8(result.stdout).unwrap(), "land\nws/a branch\n--dry-run\n--json\n");
        let result = std::process::Command::new("sh").arg(&launcher).output().unwrap();
        assert_eq!(String::from_utf8(result.stdout).unwrap(), "open\n.\n");
    }

    #[test]
    fn repo_root_resolves_from_nested_paths() {
        let dir = tempfile::tempdir().unwrap();
        let root = dir.path().canonicalize().unwrap();
        std::fs::create_dir(root.join(".jj")).unwrap();
        let nested = root.join("src/lib");
        std::fs::create_dir_all(&nested).unwrap();
        let file = nested.join("api.ts");
        std::fs::write(&file, "").unwrap();

        assert_eq!(repo_root_for(&root).as_deref(), Some(root.as_path()));
        assert_eq!(repo_root_for(&nested).as_deref(), Some(root.as_path()));
        assert_eq!(repo_root_for(&file).as_deref(), Some(root.as_path()));
    }

    #[test]
    fn repo_root_is_none_outside_any_repo() {
        let dir = tempfile::tempdir().unwrap();
        assert_eq!(repo_root_for(dir.path()), None);
    }
}
